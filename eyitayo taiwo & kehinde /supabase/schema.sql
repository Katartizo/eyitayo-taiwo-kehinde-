-- A Life in Frames: public, moderated birthday guestbook.
-- Run this in Supabase Dashboard > SQL Editor.
-- Visitors can read approved wishes and submit new pending wishes.
-- No public UPDATE or DELETE policy is provided. Approve messages in the
-- Supabase dashboard/SQL editor using a trusted admin account.

create table if not exists public.birthday_wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 60),
  relationship text,
  message text not null check (char_length(trim(message)) between 1 and 700),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.birthday_wishes enable row level security;

-- Start from least privilege, then grant only required public access.
revoke all on table public.birthday_wishes from anon, authenticated;
grant select, insert on table public.birthday_wishes to anon;
grant select on table public.birthday_wishes to authenticated;

drop policy if exists "Anyone can read approved birthday wishes" on public.birthday_wishes;
create policy "Anyone can read approved birthday wishes"
on public.birthday_wishes
for select
to anon, authenticated
using (approved = true);

drop policy if exists "Visitors can submit pending birthday wishes" on public.birthday_wishes;
create policy "Visitors can submit pending birthday wishes"
on public.birthday_wishes
for insert
to anon
with check (
  approved = false
  and char_length(trim(name)) between 1 and 60
  and char_length(trim(message)) between 1 and 700
);

-- No client policy permits changing approved=true or deleting rows.
-- To approve a specific wish, review it in the Supabase table editor and
-- change approved to true while signed into the trusted project dashboard.
-- Never put a Supabase service_role/secret key in browser JavaScript.
